"""Калькулятор материалов для кирпичной стены.

Приложение запрашивает у пользователя размеры кирпича, параметры стены
и толщину растворного шва (с возможностью использования значений по умолчанию),
после чего вычисляет:
- количество целых кирпичей,
- объём раствора (в литрах и кубических миллиметрах),
- необходимость подрезки кирпичей с учётом строительного правила:
  если остаток меньше или равен толщине шва — он заполняется раствором,
  иначе требуется подрезка кирпичей.

Результат выводится в удобочитаемом виде в терминал.
"""

from calculate_all import calculate_all


def calculate_wall_materials() -> None:
    """Запрашивает параметры, выполняет расчёт и печатает итоговую информацию.

    Данная функция служит основным оркестратором:
    - вызывает calculate_all() для получения всех расчётов,
    - форматирует вывод: количество кирпичей, объём раствора (л и мм³),
    - выводит детали по подрезке из поля 'message'.
    """
    print("\n<<--Калькулятор материалов для кирпичной стены.-->>\n")
    result = calculate_all()
    print(f"\nВсего целых кирпичей: {result['total_bricks']} шт.")
    print(f"Объём раствора: {result['mortar_volume_liters']:.1f} л ({result['mortar_volume_mm3']:,.0f} мм³)")
    print(result['trim_info']['message'])


if __name__ == "__main__":
    calculate_wall_materials()